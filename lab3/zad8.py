tekst = "Python jest super"

print(tekst[0]) #indeks zerowy

print(tekst[-1]) #indeks ostatni

print(tekst[::2]) #Co drugi zaczynając od zerowego

print(tekst[1::3]) #Co trzeci zaczynając od pierwszego

print(tekst[10:]) #Od dziesiątego do ostatniego

print(tekst[::-1]) #Wyświetl od końca do początku